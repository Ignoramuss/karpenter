package main

import (
	"errors"
	"os"
	"syscall"
)

// tryLock takes an exclusive flock on path without blocking, and reports false, with no error, while another process
// holds it. The kernel drops the lock when the last descriptor sharing it closes, so a crashed runner never leaves a
// stale lock behind.
func tryLock(path string) (*os.File, bool, error) {
	f, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR, 0o644)
	if err != nil {
		return nil, false, err
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX|syscall.LOCK_NB); err != nil {
		_ = f.Close()
		if errors.Is(err, syscall.EWOULDBLOCK) {
			return nil, false, nil
		}
		return nil, false, err
	}
	return f, true, nil
}
